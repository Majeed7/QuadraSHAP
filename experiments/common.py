"""
Shared utilities for the QuadraSHAP paper experiments.

Every experiment writes, into ``experiments/results/<name>/``:

* ``*.csv``  -- the raw per-run records (one row per instance / method / setting);
* ``*.tex``  -- booktabs tables ready to ``\\input`` into the manuscript;
* ``*.pdf``  -- figures, when matplotlib is installed (the plotting data is always
  in the CSV, so the figures can equally be produced with pgfplots);
* ``meta.json`` -- versions, seeds, hardware and timings, so that a table in the
  paper can always be traced back to the run that produced it.
"""
