# --------------------------------------------------------------------------- bookkeeping
def out_dir(name: str) -> Path:
    d = RESULTS / name
    d.mkdir(parents=True, exist_ok=True)
    return d


def git_revision() -> Optional[str]:
    try:
        return subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                                       stderr=subprocess.DEVNULL, timeout=5).decode().strip()
    except Exception:
        return None


def environment() -> Dict[str, object]:
    def ver(mod):
        try:
            return __import__(mod).__version__
        except Exception:
            return None
    return {"python": sys.version.split()[0], "platform": platform.platform(), "machine": platform.machine(),
            "processor": platform.processor() or None, "git": git_revision(),
            "numpy": ver("numpy"), "scipy": ver("scipy"), "sklearn": ver("sklearn"),
            "shap": ver("shap"), "jax": ver("jax"), "matplotlib": ver("matplotlib")}


def write_meta(name: str, **extra) -> Path:
    p = out_dir(name) / "meta.json"
    p.write_text(json.dumps({"experiment": name, "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
                             "environment": environment(), **extra}, indent=2, default=str))
    return p


def write_csv(rows: Sequence[Dict], path: Path, columns: Optional[Sequence[str]] = None) -> Path:
    import csv
    rows = [dict(r) for r in rows]
    cols = list(columns) if columns else list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k) for k in cols})
    return path


# --------------------------------------------------------------------------- LaTeX
def _fmt(v, spec: Optional[str]) -> str:
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "--"
    if isinstance(v, str):
        return v.replace("_", r"\_").replace("%", r"\%")
    if isinstance(v, (bool, np.bool_)):
        return r"\checkmark" if v else r"$\times$"
    if spec is None:
        return f"{v:g}" if isinstance(v, float) else str(v)
    if spec == "sci":  # 1.2e-05 -> $1.2\times 10^{-5}$
        if v == 0:
            return "$0$"
        s = f"{v:.1e}"
        m, e = s.split("e")
        return rf"${m}\times 10^{{{int(e)}}}$"
    return format(v, spec)


def write_latex_table(rows: Sequence[Dict], path: Path, *, columns: Sequence[str], headers: Sequence[str],
                      formats: Optional[Dict[str, str]] = None, caption: str = "", label: str = "",
                      column_format: Optional[str] = None, note: str = "", midrules_after: Sequence[int] = ()) -> Path:
    """A booktabs table ready to ``\\input`` (needs ``booktabs``; ``sci`` formats need math mode only)."""
    formats = formats or {}
    colfmt = column_format or ("l" + "r" * (len(columns) - 1))
    out = [r"% generated by the QuadraSHAP experiments -- do not edit by hand",
           r"\begin{table}[t]", r"\centering", r"\small"]
    if caption:
        out.append(rf"\caption{{{caption}}}")
    if label:
        out.append(rf"\label{{{label}}}")
    out += [rf"\begin{{tabular}}{{@{{}}{colfmt}@{{}}}}", r"\toprule",
            " & ".join(headers) + r" \\", r"\midrule"]
    for i, r in enumerate(rows):
        out.append(" & ".join(_fmt(r.get(c), formats.get(c)) for c in columns) + r" \\")
        if i + 1 in midrules_after:
            out.append(r"\midrule")
    out += [r"\bottomrule", r"\end{tabular}"]
    if note:
        out.append(rf"\\[2pt] \footnotesize {note}")
    out.append(r"\end{table}")
    path.write_text("\n".join(out) + "\n")
    return path


# --------------------------------------------------------------------------- timing
@dataclass
class Timing:
    seconds: float
    value: object


def timed(fn: Callable, *args, repeats: int = 1, **kwargs) -> Timing:
    """Median wall-clock over ``repeats`` calls (the first call is included: no warm-up by design)."""
    ts, out = [], None
    for _ in range(repeats):
        t0 = time.perf_counter()
        out = fn(*args, **kwargs)
        ts.append(time.perf_counter() - t0)
    return Timing(float(np.median(ts)), out)


# --------------------------------------------------------------------------- attribution metrics
def topk_overlap(a: np.ndarray, b: np.ndarray, k: int) -> float:
    """Fraction of the top-``k`` features by |value| that the two attributions agree on."""
    k = min(k, len(a))
    if k == 0:
        return 1.0
    ia, ib = set(np.argsort(-np.abs(a))[:k]), set(np.argsort(-np.abs(b))[:k])
    return len(ia & ib) / k


def kendall_tau(a: np.ndarray, b: np.ndarray) -> float:
    try:
        from scipy.stats import kendalltau
        return float(kendalltau(a, b).statistic)
    except Exception:  # pragma: no cover
        return float("nan")


def spearman(a: np.ndarray, b: np.ndarray) -> float:
    try:
        from scipy.stats import spearmanr
        return float(spearmanr(a, b).statistic)
    except Exception:  # pragma: no cover
        return float("nan")


def sign_agreement(a: np.ndarray, b: np.ndarray, tol: float = 0.0) -> float:
    m = (np.abs(a) > tol) | (np.abs(b) > tol)
    return float(np.mean(np.sign(a[m]) == np.sign(b[m]))) if m.any() else 1.0


def rank_metrics(phi: np.ndarray, ref: np.ndarray, ks: Sequence[int] = (1, 5, 10)) -> Dict[str, float]:
    """Agreement of an approximate attribution with a reference one."""
    out = {"max_abs_err": float(np.abs(phi - ref).max()),
           "rel_l2_err": float(np.linalg.norm(phi - ref) / max(np.linalg.norm(ref), 1e-300)),
           "kendall_tau": kendall_tau(phi, ref), "spearman": spearman(phi, ref),
           "sign_agreement": sign_agreement(phi, ref),
           "argmax_same": float(np.argmax(np.abs(phi)) == np.argmax(np.abs(ref)))}
    for k in ks:
        out[f"top{k}_overlap"] = topk_overlap(phi, ref, k)
    out["ranking_identical"] = float(np.array_equal(np.argsort(-np.abs(phi)), np.argsort(-np.abs(ref))))
    return out


def recovery_metrics(phi: np.ndarray, informative: np.ndarray, ks: Sequence[int] = (5, 10, 20)) -> Dict[str, float]:
    """How well |phi| recovers a known set of informative features (a boolean mask)."""
    score = np.abs(phi)
    out = {}
    n_inf = int(informative.sum())
    for k in ks:
        top = np.argsort(-score)[:k]
        out[f"precision@{k}"] = float(informative[top].mean())
        out[f"recall@{k}"] = float(informative[top].sum() / max(n_inf, 1))
    order = np.argsort(-score)                      # AUROC of the ranking against the informative mask
    y = informative[order].astype(float)
    pos, neg = y.sum(), len(y) - y.sum()
    # (cumsum(1-y) * y).sum() counts, for each informative feature, the uninformative ones ranked above it
    out["auroc"] = float(1.0 - (np.cumsum(1 - y) * y).sum() / (pos * neg)) if pos and neg else float("nan")
    return out


# --------------------------------------------------------------------------- synthetic data
def synthetic_regression(n: int, d: int, n_informative: int, *, seed: int = 0, scale: float = 1.0,
                         noise: float = 0.05, interactions: bool = True, amplitude: float = 1.0):
    """Standardised features; the target is built from ``n_informative`` features and scaled to std ``scale``.

    ``amplitude`` multiplies the informative columns: with an isotropic RBF kernel in ``d`` dimensions
    the distance is otherwise dominated by the noise coordinates and the fitted model generalises
    poorly, which would make a comparison against the *generative* ground truth meaningless.

    Returns ``(X, y, informative_mask)``.
    """
    rng = np.random.default_rng(seed)
    X = rng.standard_normal((n, d))
    idx = rng.choice(d, size=n_informative, replace=False)
    X[:, idx] *= amplitude
    beta = rng.standard_normal(n_informative) * np.linspace(1.5, 0.5, n_informative)
    y = X[:, idx] @ beta
    if interactions and n_informative >= 4:        # a little non-linearity, so a kernel model is warranted
        y += 1.5 * np.sin(X[:, idx[0]] * X[:, idx[1]] / amplitude ** 2) + 0.8 * (X[:, idx[2]] / amplitude) ** 2
    y = (y - y.mean()) / y.std()
    y = scale * (y + noise * rng.standard_normal(n))
    mask = np.zeros(d, dtype=bool)
    mask[idx] = True
    return X, y, mask


def fit_krr(X, y, *, gamma_scale: float = 1.0, alpha: float = 0.1):
    """RBF kernel ridge with ``gamma = gamma_scale / d`` (the bandwidth drives Lambda, hence the node budget)."""
    from sklearn.kernel_ridge import KernelRidge
    return KernelRidge(kernel="rbf", gamma=gamma_scale / X.shape[1], alpha=alpha).fit(X, y)


# --------------------------------------------------------------------------- figures
def figure(path: Path, *, figsize=(5.2, 3.4)):
    """Context-manager-free helper: returns ``(fig, ax)`` or ``(None, None)`` when matplotlib is missing."""
    if not MATPLOTLIB:
        return None, None
    fig, ax = plt.subplots(figsize=figsize)
    return fig, ax


def save_figure(fig, path: Path) -> Optional[Path]:
    if fig is None:
        return None
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    return path


def log_line(msg: str) -> None:
    print(msg, flush=True)
